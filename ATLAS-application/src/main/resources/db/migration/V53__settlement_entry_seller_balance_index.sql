-- 판매자 정산 잔액 조회의 전체 스캔을 제거한다.
--
-- sellerBalance 는 판매자의 모든 settlement_entry 를 SUM 한다. seller_id 인덱스가 없으면
-- 이력이 쌓일수록 매 조회가 테이블 전체를 스캔한다. EXP-045 측정(4,600행):
--   Seq Scan 2,936 버퍼 → 인덱스 4 버퍼 (734배 감소).
-- 운영 데이터 규모에서는 판매자 지급·명세 화면이 사실상 응답하지 않게 된다.
--
-- 왜 (seller_id, account_code, entry_side) 인가: sellerBalance 의 WHERE 는 seller_id 이고
-- CASE 가 account_code·entry_side 로 분기한다. 세 컬럼으로 후보 행을 인덱스에서 좁힌다.
--
-- 한계(정직하게): amount_won 을 포함하지 않으므로 순수 Index Only Scan 은 아니다. 인덱스로
-- 후보를 찾은 뒤 판매자 이력 건수만큼 heap 을 읽는다. 측정한 4,600행에서는 2,936 → 4 버퍼로
-- 충분했지만, 판매자당 이력이 수십만 건이 되면 여전히 O(이력) 이다. 그 시점의 해법은
-- settlement_seller_balance rollup(insertEntry 와 같은 transaction 에서 증분 갱신)이다.
-- 이 마이그레이션은 그 전 단계의 즉시 개선이며, 그 한계를 여기 남긴다.
--
-- 왜 일반 CREATE INDEX 인가: 이 저장소의 기존 인덱스 마이그레이션(V39, V41, V42)이 같은
-- 방식을 쓴다. settlement_entry 는 Flyway 기동 시점에 쓰기 트래픽이 없고, 원장은 배포
-- 직후가 아니라 애플리케이션 기동 완료 후에만 쓰인다. CONCURRENTLY 는 transaction 밖 실행이
-- 필요해 Flyway 설정 변경이 선행돼야 하므로, 운영 무중단이 요구되면 별도 작업으로 분리한다.
--
-- 롤백 시 되돌리기: DROP INDEX IF EXISTS settlement_entry_seller_account_side_idx;
CREATE INDEX IF NOT EXISTS settlement_entry_seller_account_side_idx
    ON settlement_entry (seller_id, account_code, entry_side);
